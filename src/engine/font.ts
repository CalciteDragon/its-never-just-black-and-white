/** Resolve a character to its glyph rows (lowercase → uppercase, unknown → box). */
export function glyphFor(ch: string): readonly string[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? FALLBACK_GLYPH;
}

/** Pixel width of a string at the given scale (1px spacing between glyphs). */
export function measureText(text: string, scale = 1): number {
  let w = 0;
  let n = 0;
  for (const ch of text) {
    w += glyphFor(ch)[0].length;
    n++;
  }
  if (n > 1) {
    w += (n - 1) * GLYPH_SPACING;
  }
  return w * scale;
}

/** Draw text with per-pixel fillRects. y is the top of the glyph line. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  let penX = x;
  for (const ch of text) {
    const rows = glyphFor(ch);
    const w = rows[0].length;
    for (let ry = 0; ry < rows.length; ry++) {
      const row = rows[ry];
      for (let rx = 0; rx < row.length; rx++) {
        if (row[rx] === '#') {
          ctx.fillRect(penX + rx * scale, y + ry * scale, scale, scale);
        }
      }
    }
    penX += (w + GLYPH_SPACING) * scale;
  }
}

/** Draw text horizontally centered on cx. */
export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawText(ctx, text, Math.round(cx - measureText(text, scale) / 2), y, color, scale);
}
